def cnum(s):
    if s == '十':
        return 10
    if '十' in s:
        a, _, b = s.partition('十')
        return (D.get(a, 1) if a else 1) * 10 + D.get(b, 0)
    return D[s]


def han(s):
    return len(HAN.findall(s))


