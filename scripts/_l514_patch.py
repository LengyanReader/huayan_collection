# -*- coding: utf-8 -*-
"""_l514_patch.py — L.514 修正：①孤立 ## 五、 残行；②窗1/窗2 按语与实际窗口对齐"""
import glob, io, re, sys
sys.stdout.reconfigure(encoding='utf-8')

fp = None
for g in glob.glob('docs/经学文献/华严经细读/第六会_他化自在天宫_十地位/华严经细读_第二十六部_*.md'):
    fp = g
md = io.open(fp, encoding='utf-8').read()

# ① 孤立 ## 五、
before = md.count('\n## 五、\n## 五、')
assert before == 1, before
md = md.replace('\n## 五、\n## 五、', '\n## 五、', 1)

# ② 窗1 按语
old0 = '> **按语**〔本文判断〕澄观科初地文八分（第八名為校量勝分）；并判行布圆融——「地地之中。具足一切諸地功德。寧許初地不持戒等」；十愿「此願亦即是行。稱願行故。非如凡夫空有要期」——愿门为首、愿行相成。'
new0 = '> **按语**〔本文判断〕澄观答「如何諸分地地皆通」——行布圆融判：「地地之中。具足一切諸地功德。寧許初地不持戒等」（纵读行布·横读圆融）；科初地文八分·第八名為校量勝分；論經別行具六成就·今攝在大部故闕信聞——校量顯示勝故·在於初時及勝處說。'
assert old0 in md
md = md.replace(old0, new0, 1)

# ③ 窗2 按语
old1 = '> **按语**〔本文判断〕二地来意三重：依初地见道修三学·戒最在初·十度次第（前施此戒·下之八地依十度）；离垢三义（因离·果行离·对治离）；**断邪行障·证最勝真如·皆约戒明**。'
new1 = '> **按语**〔本文判断〕此窗为诸地名义连释：离垢三义（因离·果行离·对治离）＋三慧照当境名「明地」；唯識释發光「成就勝定大法總持。能發無邊妙慧光」；焰地「根本智火能燒前地」·難勝「真俗無違極難勝故」——二地之名义与此窗后段诸名连类而释·来意窗别见 §5.2。'
assert old1 in md
md = md.replace(old1, new1, 1)

io.open(fp, 'w', encoding='utf-8', newline='').write(md)
print('patch ok:', md.count('## 五、'), md.count('圖 〇-3'), md.count('图 〇-3'))
