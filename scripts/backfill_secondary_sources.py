def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    cur.execute("PRAGMA foreign_keys=ON")

    # ---- A. 数据卫生 ----
    n_del = 0
    for eid in DELETE_EDGE_IDS:
        cur.execute("SELECT id,from_person_id,to_person_id FROM lineage_edges WHERE id=?", (eid,))
        if cur.fetchone():
            cur.execute("DELETE FROM lineage_edges WHERE id=?", (eid,))
            n_del += 1
    print("删除边: %d" % n_del)

    # ---- B. 回填 ----
    skip_e = skip_p = 0
    for name, (src, verified) in PERSONS.items():
        if not cur.execute("SELECT 1 FROM persons WHERE name_zh=?", (name,)).fetchone():
            skip_p += 1
            print("  skip person:", name)
            continue
        cur.execute("UPDATE persons SET source=?, verified=? WHERE name_zh=?", (src, verified, name))
    for (frm, to, rel), src in EDGES.items():
        cur.execute("""UPDATE lineage_edges SET source=?
                       WHERE from_person_id=(SELECT source_id FROM persons WHERE name_zh=?)
                         AND to_person_id=(SELECT source_id FROM persons WHERE name_zh=?)
                         AND relation=?""", (src, frm, to, rel))
        if cur.rowcount == 0:
            skip_e += 1
            print("  skip edge:", frm, "→", to, rel)
    con.commit()
    print("Done: persons=%d edges=%d skip_person=%d skip_edge=%d"
          % (len(PERSONS), len(EDGES), skip_p, skip_e))
    con.close()


if __name__ == "__main__":
    main()