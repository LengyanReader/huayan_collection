# -*- coding: utf-8 -*-
"""enrich_quant4.py — L.472 批C：量学四品（P28/30/31/32）义理要点增写〔本文判断〕"""
import io, re, sys, glob
sys.stdout.reconfigure(encoding='utf-8')

APPLY = '--apply' in sys.argv

ESSAYS = {
    '第三十部': (
        '【数量观·通释之一：以数废数】（〔本文判断〕）本品与品31〈壽量〉、品32〈諸菩薩住處〉、品28〈十通〉'
        '合观，可称「量学四品」——华严以四种量（数·时·处·通）把不可说逼到语言边界。本品以数废数：'
        '一百二十余重数法递进至「不可说不可说转」，每一级都仍是数，却层层宣告数的失效——数到极处，数即是遮。'
        '数之所以可立，皆由能所对立；能所双泯，则「阿僧祇」一名亦当捨。故此品读法不在数而在观——'
        '观「数之所以不可数」。'),
    '第三十一部': (
        '【数量观·通释之二：以短说长】（〔本文判断〕）302 字的底本与无量之寿构成全经最大反差——'
        '这正是本品的修辞策略：以最少的字说最久的时间。三重递进（别举十剎相望→举略显广→举其玄极）'
        '每重都以「以劫为日」式换算把量纲打碎；至「沈百萬僧祇则最后之刹」而止笔——止笔即极端，'
        '极端处语言自弃。与品30 合观：彼以数之递进显不可数，此以时之换算显不可量；'
        '经文愈短，指向愈长——篇幅本身就是义理的一部分。'),
    '第三十二部': (
        '【数量观·通释之三：以处摄人】（〔本文判断〕）七百余字列菩萨住处——每一处有名、有菩萨、'
        '有眷属数量，形式近乎地理志，实则以「处」摄「人」：凡有名可指处，皆菩萨遍在之证。'
        '而「毛端含剎海」之旨（澄观疏语）提示：名处是指月之指，住处并非实有方所。'
        '与品31 合观：彼明寿量无际（时），此明住处遍在（处）——时空双彰，同答果海之坐标。'
        '读此品宜如读地图而不住于地图：逐处检索，最后忘处。'),
    '第二十八部': (
        '【数量观·通释之四：以念念摄刹海】（〔本文判断〕）十种通皆以「於一念中」为句式枢纽——'
        '他心智、天眼、宿住、知劫……每一通都把无量世界压缩进一念。通之所以为通，'
        '不在功能之奇异，而在量之自由：念与刹海互不妨碍，一多相即而无踪迹。'
        '与品30/31/32 合观：数（阿僧祇）·时（壽量）·处（住處）·通（十通）四品同答第二会初'
        '「如來地等二十句問」之果分——量学四品实为一组：数废、时长、处遍、通圆，'
        '四种量各自走到语言尽头，会同于「不思议」一名。'),
}

for key, essay in ESSAYS.items():
    g = glob.glob('docs/经学文献/华严经细读/**/华严经细读_%s_*.md' % key, recursive=True)
    if not g:
        print(key, 'md 未定位'); continue
    fp = g[0]
    md = io.open(fp, encoding='utf-8').read()
    if essay[:20] in md:
        print(key, '已存在·跳过'); continue
    i5 = md.find('\n## 五、注疏选要')
    if i5 < 0:
        print(key, '未找到注疏节'); continue
    md = md[:i5] + '\n' + essay + '\n' + md[i5:]
    if APPLY:
        io.open(fp, 'w', encoding='utf-8', newline='').write(md)
    print(key, 'OK', '+%d 字' % len(re.findall(r'[\u3400-\u9fff]', essay)))

print('== 干跑 ==' if not APPLY else '== 已写入 ==')
