"""_p37_fix_a.py — L.509 P37 优化 A：智俨错章替换＋合论结构化＋§6.1 深化"""
import io, re, json, unicodedata

fp = 'docs/经学文献/华严经细读/第七会_普光明殿_等觉/华严经细读_第三十七部_如来出现品.md'
md = io.open(fp, encoding='utf-8').read()

# ══ 1) §5.2 智俨错章引文 → 正确性起品窗（T1732@109324）══
t = io.open('data/references/cbeta_txt/T1732_智俨_搜玄记.txt', encoding='utf-8').read()
t = re.sub(r'<<<PAGE \d+>>>', '', t)
t = unicodedata.normalize('NFKC', t)
a = t.find('寶王如來性起品第三十二')
w = t[a:a+900]
acc = 0
for i, ch in enumerate(w):
    if re.match(r'[\u3400-\u9fff]', ch):
        acc += 1
    if acc >= 700 and ch in '。！」』':
        w = w[:i+1]
        break
HAN = lambda s: len(re.findall(r'[\u3400-\u9fff]', s))
zy_new = ('**智俨《華嚴經搜玄分齊通智方軌》（`T1732`·二祖早期疏释）——〈寶王如來性起品〉释**（%d 字·程序抽取逐字回源·句界截断）：\n\n> %s\n\n'
          '> **按语**〔本文判断〕智俨以「性者體。起者現在心地」解题——性起之「起」不在外缘而在心地现前；'
          '「性起分齊」开始终/阔狭二义（始自发心至佛性起，阔狭顿悟及三乘始终、世间下至地狱）；'
          '并辨「二处不生根」——不生者不生菩提心性起芽、不言无果叶，「若无者微尘中不应有经卷」'
          '——**微尘经卷喻正是性起分齐之证**，与八十本品大经卷喻直通。\n' % (HAN(w), w))
pat_zy = re.compile(r'\*\*智俨《華嚴經搜玄分齊通智方軌》（T1732·二祖早期疏释）\*\*（903 字·程序抽取逐字回源·句界截断）：\n\n> .*?\n\n……（后文从略）\n', re.S)
assert pat_zy.search(md), 'zhiyan block not found'
md = pat_zy.sub(lambda m: zy_new, md, 1)
print('1 zhiyan replaced')

# ══ 2) 李通玄合论 3191 字 dump → 结构化两引 ══
mhl = re.search(r'\*\*李通玄《華嚴經合論》\*\*（3191 字·程序抽取·句界截断）：\n\n> (.*?)\n\n……（后文从略）\n', md, re.S)
assert mhl, 'helun block not found'
raw = mhl.group(1)
k = raw.find('第四明成佛同別')
q1 = raw[:k]
q2 = raw[k:]
hl_new = ('**李通玄《華嚴經合論》·甲 生如来家与付嘱大心凡夫**（%d 字·程序抽取·照录）：\n\n> %s\n\n'
          '**按语**〔本文判断〕李论以转轮圣王七宝喻判此经所付：**唯付「生如来家、种如来相」之大心凡夫**——「若无大心凡夫求此法门生如来家，此经当灭」；三乘之教付嘱诸圣，此经付嘱凡夫入证者，方名流通。\n\n'
          '**李通玄《華嚴經合論》·乙 成佛同别十门**（%d 字·程序抽取·照录）：\n\n> %s\n\n'
          '**按语**〔本文判断〕李论成道同别十门（身/时/树/座/众/示相/转法轮/处/大会庄严/所授法门）逐门拣三乘权教与一乘实报——正显「如来出现」非八相成道之出现，乃**本法界无始无终之现起**：「如來不出世亦無有涅槃此為實說」。\n'
          % (HAN(q1), q1, HAN(q2), q2))
md = md.replace(mhl.group(0), hl_new, 1)
print('2 helun structured')

# ══ 3) §6.1 六十性起品深化 ══
d60 = json.load(open('web/demo/data/sutra/c60/p032.json', encoding='utf-8'))
t60 = '\n'.join(p for s in d60['segs'] for p in s['paras'])
i卷 = t60.find('經卷')
seg60 = re.sub(r'\s+', '', t60[max(0, i卷-150):i卷+550])
head60 = re.sub(r'\s+', '', t60[:400])
sec61 = ('''### 6.1 六十华严（`T0278`〈寶王如來性起品第三十二〉）

**品题与新旧译对照**：「性起」（六十·晉譯）与「出現」（八十·唐譯）同出一梵语原义之两译——澄观释云「是以晉經名性起，性字雖是義加，未爽通理……以淨奪染性即起故」（§2.0′）；智俨释「性者體，起者現在心地」（§5.2）。〔本文判断〕「性起」显**本然现起**义（对治缘起造作读法），「出現」显**果用现前**义（含化用），二题各有所重，唐译改题或兼为答〈不思議品〉出現念故。

**六十·品首**（`T0278`·照录）：

> %s……

**六十·微尘经卷喻**（`T0278`·照录·与八十 §2.7 大经卷喻对读）：

> %s……

**对照要点**（〔本文判断〕）：①两译同有微尘经卷喻——「一尘一卷」义两译无别；②六十品题冠「寶王」（攝德自在），八十直题「如來出現」；③八十本品九段（身/音声/心/境界/行/菩提/转法轮/般涅槃/见闻）结构，六十〈性起品〉以同经异译存其义而科分不同——逐段全量对勘〔未竟〕。
''' % (head60, seg60))
old61 = '### 6.1 六十华严（`T0278`〈性起品〉）\n\n新旧译对应关系：「性起」与「出現」同一梵语原义之两译〔本文判断〕——逐段对勘待深化批〔未竟〕。'
assert old61 in md, '6.1 not found'
md = md.replace(old61, sec61, 1)
print('3 6.1 deepened')

io.open(fp, 'w', encoding='utf-8', newline='').write(md)
print('phase A done')
