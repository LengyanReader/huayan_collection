RAD = {
    '\u2ef6': '日', '\u2ef7': '月', '\u2ed1': '長', '\u2ec5': '門', '\u2eda': '頁',
    '\u2edb': '風', '\u2ed8': '飛', '\u2ec3': '食', '\u2e80': '丨', '\u2e97': '冓',
    '\u2f71': '魚', '\u2f73': '鳥', '\u2f77': '鹵', '\u2f7a': '鹿',
}


def norm(s):
    s = unicodedata.normalize('NFKC', s)
    return ''.join(RAD.get(ch, ch) for ch in s)


SRC = {}


def load(key):
    if key == '六十':
        ps = [os.path.join(YD, '六十华严_1.txt')]
    elif key == '简本':
        ps = [os.path.join(YD, '八十华严-简-大华严寺袖珍版_1.txt')]
    elif key == '繁本':
        ps = [os.path.join(YD, '八十华严-繁-大华严寺袖珍版_1.txt')]
    elif key == '海云五':
        ps = [os.path.join(HAI_DIR, '05佛陀的花园（华严经世主妙严品卷五讲记）_1.txt')]
    elif key == '海云':
        ps = [os.path.join(HAI_DIR, f) for f in sorted(os.listdir(HAI_DIR)) if f.endswith('.txt')]
    else:
        ps = [os.path.join(CB, f) for f in os.listdir(CB) if f.startswith(key + '_')]
    txt = ''.join(open(p, encoding='utf-8').read() for p in ps)
    txt = re.sub(r'<<<PAGE \d+>>>', '', txt)
    txt = re.sub(r'\s+', '', txt)
    return norm(txt)


def get(key):
    if key not in SRC:
        SRC[key] = load(key)
    return SRC[key]


