def main():
    out = []
    for g, specs in GROUPS.items():
        out.append('\n\n########## %s ##########' % g)
        for label, key, anchors in specs:
            t = get(key)
            hit = None
            for a in anchors:
                i = t.find(norm(a))
                if i >= 0:
                    hit = (a, t[max(0, i - BEFORE): i + AFTER])
                    break
            out.append('---- %s [%s] ----\n%s' % (
                label, hit[0] if hit else 'MISS', hit[1] if hit else '(未命中)'))
    open(os.path.join(BASE, 'scripts', '_v5_out.txt'), 'w', encoding='utf-8').write('\n'.join(out))
