"""_p37_fix_b.py — L.509 P37 优化 B：〇之二.9 归位＋§2.0′ 十标＋5.2 对读小结＋台账"""
import io, re

fp = 'docs/经学文献/华严经细读/第七会_普光明殿_等觉/华严经细读_第三十七部_如来出现品.md'
md = io.open(fp, encoding='utf-8').read()

# ══ 4) 〇之二.9 错置归位（§五 中间 → 〇之二.8 之后）══
m9 = re.search(r'\n### 〇之二\.9 文化资产参证（名胜·造像·图绘·L\.441 落位）\n(?:(?!\n### |\n## ).)*', md, re.S)
assert m9, 'block .9 not found'
blk9 = m9.group(0)
md = md.replace(blk9, '\n', 1)
m8 = re.search(r'(### 〇之二\.6 [^\n]*\n(?:(?!\n### |\n## ).)*)', md, re.S)
assert m8, 'block .6 not found'
md = md.replace(m8.group(1), m8.group(1).rstrip() + '\n' + blk9.rstrip() + '\n', 1)
print('4 .9 moved to 0-2 series')

# ══ 5) §2.0′ 十标（疏切片结构化）══
marks = [
 ('第二會所行問故。會釋如前。二釋名者', '◆ 疏·釋名（十身皆有出現·晉經名性起）'),
 ('第三宗趣者，平等出現為宗', '◆ 疏·宗趣＋正釋文七分之一加分（毫光加請主·口光加說主）'),
 ('第二「爾時」下本分', '◆ 疏·七分之二本分（徵事而問·引例以答）'),
 ('第三「時性起」下請分', '◆ 疏·七分之三請分（總舉法請·標章別請十事）'),
 ('第四說分。大分為二', '◆ 疏·七分之四說分（別答十問：身/音聲/心/境界/行/菩提/轉法輪/般涅槃…總以結酬）'),
 ('大文第五「佛子此法門」下顯名受持分', '◆ 疏·七分之五顯名受持分（十名五對·法器揀擇）'),
 ('大文第六現瑞證成', '◆ 疏·七分之六表瑞證成分（果人證＋因人證）'),
 ('大文第七「爾時普賢」下以偈總攝', '◆ 疏·七分之七偈頌總攝（十門出現·勸持）'),
]
cnt = 0
for anchor, label in marks:
    i = md.find(anchor)
    if i < 0:
        print('  miss marker:', anchor[:20])
        continue
    ins = '> **◆ ' + label + '**\n>\n'
    # 找该段行首（向前找最近的 '\n> ' 行首）
    j = md.rfind('\n> ', 0, i + 3)
    if j < 0:
        continue
    md = md[:j] + '\n' + ins + md[j+1:]
    cnt += 1
print('5 markers inserted:', cnt)

# ══ 6) 5.2 末对读小结（插在 5.9 之前）══
summary = '''### 5.2′ 诸家对读小结（L.509）

| 家 | 判旨 | 与本品之切要 |
|---|---|---|
| 澄观《疏》（§2.0′） | 性起＝果用化用总名；晉經名性起「性字雖是義加」 | 釋名三身明「出現」；性起妙德菩萨＝文殊大智能显、普贤法界所显 |
| 智俨《搜玄记》 | 「性者體。起者現在心地」 | 性起分齊始终/阔狭二义；微尘经卷喻为性起分齐之证 |
| 李通玄《新华严经论》（§5.2 前引） | 五度重叙普光明殿＝法界性相根本智不二 | 不移本处而遍坐一切处 |
| 李通玄《合論》 | 付嘱大心凡夫；成佛同别十门 | 「如來不出世亦無有涅槃此為實說」——出现非八相成道 |
| 道霈《纂要》 | 涅槃五别（释名/出体/种类…） | 大涅槃三德具如天目伊字——出现之归宿 |

> **对读要义**〔本文判断〕：诸家同以本品为「性起」之果分——澄观、智俨释**性起题义**，李通玄判**出现与成道之同别**，道霈收**涅槃为出现之终**；四家合读，「出现＝性起＝非造作之现起」一义贯穿。
'''
m59 = re.search(r'\n### 5\.9 新加坡白话浅释选录', md)
assert m59
md = md[:m59.start()+1] + summary + '\n' + md[m59.start()+1:]
print('6 summary added')

# ══ 7) 台账 ══
old_t = '## 九、台账（成篇自陈）'
assert old_t in md
md = md.replace(old_t, '''## 九、台账（成篇自陈）

- **L.509（2026-11-18）结构优化批**：①§5.2 智俨引文**错章纠正**（原窗为〈離世間品第三十三〉释·实为 L.310/L.314 取窗错位；今改取 T1732〈寶王如來性起品〉释·「性者體起者現在心地」＋性起分齊二义＋微尘经卷证）；②李通玄《合論》3191 字长引**结构化**为甲（生如来家付嘱）乙（成佛同别十门）两引＋按语；③**§6.1 六十〈性起品〉深化**（品首＋微尘经卷喻照录＋新旧译题义辨＋对照要点三则）；④〇之二.9 文化资产参证自 §五 错位**归位**〇之二 系列末；⑤§2.0′ 疏切片增 **十处界标**（釋名/宗趣加分/本分/請分/說分/顯名受持/現瑞證成/偈頌總攝）——七百行疏墙自此可导航；⑥新增 5.2′ 诸家对读小结（五家判旨表＋对读要义）。''', 1)

io.open(fp, 'w', encoding='utf-8', newline='').write(md)
print('phase B done')
