def main():
    frag = io.open(".tmp_t1_quotes.frag", encoding="utf-8").read()
    # 〔L109·坑〕frag 经 shell 重定向会成 CRLF，故须先归一行尾，
    # 否则按 "\n  - id: " 切分必然失配（且失配表现为「judgments 缺 C01」，
    # 误导为 judgments 不全——实为切分器之错）。
    frag = frag.replace("\r\n", "\n").replace("\r", "\n")
    blocks = []
    done = []
    for blk in frag.split("\n  - id: "):
        if not blk.strip():
            continue
        # 首块无 "\n  - id: " 前缀，须同样剥除，否则 bid 变成 "- id: C01"
        if blk.startswith("  - id: "):
            blk = blk[len("  - id: "):]
        bid = blk.split("\n")[0].strip()
        if bid not in JUDG:
            raise SystemExit("【judgments 缺 %s】" % bid)
        key, sec = JUDG[bid]
        body = blk[blk.find("\n"):].rstrip()
        # 去掉 frag 里已有的 sec 行（以 judgments 为准）
        body = "\n".join(x for x in body.split("\n")
                         if not x.strip().startswith("sec:"))
        assert '"' not in key, "key 含双引号：%s" % bid
        blocks.append('  - id: %s\n%s\n    key: "%s"\n    sec: "%s"'
                      % (bid, body, key, sec))
        done.append(bid)
    miss = set(JUDG) - set(done)
    extra = set(done) - set(JUDG)
    if miss or extra:
        raise SystemExit("【对账失败】缺 %s／多 %s"
                         % (sorted(miss), sorted(extra)))
    out = HEAD + "\n".join(blocks) + "\n" + NEG
    path = "data/research/t1_bikan_evidence.yaml"
    io.open(path, "w", encoding="utf-8", newline="\n").write(out)
    print("已写 %s（%d 条引文，%d 字节）"
          % (path, len(blocks), len(out.encode("utf-8"))))


if __name__ == "__main__":
    main()
