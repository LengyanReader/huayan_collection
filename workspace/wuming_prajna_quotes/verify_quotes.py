XML_DIR = os.path.normpath(os.path.join(HERE, os.pardir, os.pardir, 'data', 'references', 'cbeta'))

PUNCT = set('，。、；：？！「」『』（）《》〈〉……—－·“”‘’ \u3000\n\r\t()[]')

def load_text(tid):
    p = os.path.join(XML_DIR, tid + '.xml')
    xml = open(p, encoding='utf-8').read()
    t = re.sub(r'<[^>]+>', '', xml)
    t = re.sub(r'&[a-zA-Z#0-9]+;', '', t)
    return t

def strip_punct(s):
    return ''.join(ch for ch in s if ch not in PUNCT)

def find_ctx(text, needle, before=18, after=30):
    """在原文 text 中找 needle（标点无关），返回原文上下文。"""
    hay = text
    hay_np = strip_punct(hay)
    nd_np = strip_punct(needle)
    idx = hay_np.find(nd_np)
    if idx < 0:
        return None
    # 回映：hay_np 第 idx 字符对应 hay 中的位置
    pos_map = []
    for i, ch in enumerate(hay):
        if ch not in PUNCT:
            pos_map.append(i)
    if idx >= len(pos_map):
        return None
    start = pos_map[idx]
    end = pos_map[min(idx + len(nd_np) - 1, len(pos_map) - 1)] + 1
    lo = max(0, start - before)
    hi = min(len(hay), end + after)
    return hay[lo:hi].replace('\n', '⏎')

