def rep(a, b, tag, expect=1):
    global s
    n = s.count(a)
    if n != expect: raise SystemExit('FAIL(%d!=%d) %s: %s' % (n, expect, tag, a[:50]))
    s = s.replace(a, b)
    LOG.append('%s (x%d)' % (tag, expect))

